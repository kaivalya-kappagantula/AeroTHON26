#!/usr/bin/env bash
# oa_eval.sh — BendyRuler vs path_planner in SITL, tests 3-5 of
# docs/OA_EVALUATION.md. Each run: fresh SITL (wiped eeprom, the planner's FC
# parameter set loaded at boot) + MAVROS + oa_eval.launch.py, one corridor
# pass, scored by oa_eval_node, everything killed. Results append to
# <out>/results.jsonl; the summary table is printed at the end
# (oa_eval_report.py, re-run it any time on the same file).
#
# WARNING: kills any running sim_vehicle / arducopter / MAVROS / ROS nodes of
# this stack first. Run it when you own the box.
#
#   scripts/oa_eval.sh --planner bendy   --scenario centred                 # test 3
#   scripts/oa_eval.sh --planner bendy   --scenario staggered               # test 4
#   scripts/oa_eval.sh --planner bendy   --scenario staggered --runs 10 \
#                      --spacing 2.0,2.5,3.0 --dropout 0.2                  # test 5
#   scripts/oa_eval.sh --planner current ...                                # same, baseline
#   scripts/oa_eval.sh --planner bendy --scenario centred \
#                      --set OA_MARGIN_MAX=0.35 --set OA_BR_LOOKAHEAD=2     # tuning
#
# Options:
#   --planner bendy|current   (default bendy)
#   --scenario centred|staggered|empty   (default centred)
#   --runs N                  (default 1) runs, cycling through --spacing values
#   --spacing a,b,...         staggered front-face spacing(s), m (default 2.5)
#   --dropout F               fraction of depth pixels dropped (default 0)
#   --set NAME=VALUE          FC parameter override (repeatable) on top of the set
#   --launch-arg k:=v         extra oa_eval.launch.py argument (repeatable)
#   --out DIR                 (default ~/oa_eval/<date>)
#   --label TEXT              free text stored with each result (e.g. "margin 0.35")
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PKG="$(cd "$HERE/.." && pwd)"
ARDUPILOT_DIR="${ARDUPILOT_DIR:-$HOME/ardupilot}"
WS="${WS:-${AEROTHON_ROOT:-$HOME/AeroTHON26}/ros2_ws}"
LOCATION="12.9716,77.5946,0,0"          # = sitl_corridor_sim origin, nose North
RUN_TIMEOUT_S=420

PLANNER=bendy; SCENARIO=centred; RUNS=1; SPACING=2.5; DROPOUT=0.0
SETS=(); LARGS=(); OUT="$HOME/oa_eval/$(date +%Y%m%d)"; LABEL=""
while [[ $# -gt 0 ]]; do
    case $1 in
        --planner)    PLANNER="$2"; shift 2 ;;
        --scenario)   SCENARIO="$2"; shift 2 ;;
        --runs)       RUNS="$2"; shift 2 ;;
        --spacing)    SPACING="$2"; shift 2 ;;
        --dropout)    DROPOUT="$2"; shift 2 ;;
        --set)        SETS+=("$2"); shift 2 ;;
        --launch-arg) LARGS+=("$2"); shift 2 ;;
        --out)        OUT="$2"; shift 2 ;;
        --label)      LABEL="$2"; shift 2 ;;
        -h|--help)    sed -n 2,33p "$0"; exit 0 ;;
        *) echo "unknown option $1" >&2; exit 1 ;;
    esac
done
case $PLANNER in
    bendy)   BASE="$PKG/params/bendyruler_eval.param" ;;
    current) BASE="$PKG/params/stage5_6_corridor.param" ;;
    *) echo "--planner bendy|current" >&2; exit 1 ;;
esac
IFS=, read -r -a SPACINGS <<< "$SPACING"
mkdir -p "$OUT"
RESULTS="$OUT/results.jsonl"

log(){ echo -e "\n=== $* ==="; }
killall_stack(){
    pkill -f "sim_vehicle|arducopter|mavros_node|oa_eval_node|sitl_corridor_sim|sim_depth_dropout|sector_builder_node|obstacle_publisher_node|coverage_guard_node|corridor_perception_node|path_planner_node|static_transform_publisher" 2>/dev/null
    sleep 2
    pkill -9 -f "sim_vehicle|arducopter|mavros_node|oa_eval_node|sitl_corridor_sim|sim_depth_dropout|sector_builder_node|obstacle_publisher_node|coverage_guard_node|corridor_perception_node|path_planner_node|static_transform_publisher" 2>/dev/null
}
trap 'killall_stack; exit 130' INT TERM

set +u
source /opt/ros/jazzy/setup.bash
source "$WS/install/setup.bash"
set -u

# FC parameter file for this batch: the base set with --set lines replacing
# theirs (one value per name, so there is no doubt which one SITL used).
PARAMS="$OUT/fc_${PLANNER}_$(date +%H%M%S).param"
OVERRIDE_NAMES=()
for s in "${SETS[@]+"${SETS[@]}"}"; do OVERRIDE_NAMES+=("${s%%=*}"); done
{
    echo "# generated by oa_eval.sh from $(basename "$BASE") ${SETS[*]+${SETS[*]}}"
    while read -r line; do
        name="${line%%[[:space:]]*}"
        skip=0
        for o in "${OVERRIDE_NAMES[@]+"${OVERRIDE_NAMES[@]}"}"; do [[ "$name" == "$o" ]] && skip=1; done
        [[ $skip == 0 ]] && echo "$line"
    done < "$BASE"
    for s in "${SETS[@]+"${SETS[@]}"}"; do echo "${s%%=*} ${s#*=}"; done
} > "$PARAMS"
FC_SETS="$(grep -v '^#' "$PARAMS" | awk 'NF==2{printf "%s=%s ", $1, $2}')"
echo "FC parameters ($PARAMS): $FC_SETS"

for ((i = 0; i < RUNS; i++)); do
    sp="${SPACINGS[$((i % ${#SPACINGS[@]}))]}"
    RUN="$(date +%H%M%S)_${PLANNER}_${SCENARIO}_$i"
    RUN_DIR="$OUT/$RUN"; mkdir -p "$RUN_DIR"
    log "run $((i + 1))/$RUNS: $PLANNER, $SCENARIO, spacing $sp m, dropout $DROPOUT -> $RUN_DIR"
    killall_stack

    # Fresh SITL per run: -w wipes the eeprom, the param file is applied at
    # boot (PRX1_TYPE / OA_TYPE need a reboot otherwise). Logs land in RUN_DIR.
    ( cd "$RUN_DIR" && python3 "$ARDUPILOT_DIR/Tools/autotest/sim_vehicle.py" \
        -v ArduCopter -f quad --no-mavproxy --no-rebuild -w -l "$LOCATION" \
        --add-param-file="$PARAMS" > "$RUN_DIR/sitl.log" 2>&1 ) &
    for _ in $(seq 1 90); do (echo >/dev/tcp/127.0.0.1/5760) 2>/dev/null && break; sleep 1; done
    if ! (echo >/dev/tcp/127.0.0.1/5760) 2>/dev/null; then
        echo "SITL never opened 5760 (see $RUN_DIR/sitl.log)"; continue
    fi

    before=$(wc -l < "$RESULTS" 2>/dev/null || echo 0)
    tags="{\"label\": \"$LABEL\", \"run\": \"$RUN\", \"fc\": \"$FC_SETS\"}"
    ros2 launch mission_bringup oa_eval.launch.py \
        planner:="$PLANNER" scenario:="$SCENARIO" spacing_m:="$sp" dropout:="$DROPOUT" \
        result_file:="$RESULTS" trace_file:="$RUN_DIR/trace.csv" tags:="$tags" \
        "${LARGS[@]+"${LARGS[@]}"}" > "$RUN_DIR/ros.log" 2>&1 &
    LPID=$!
    t0=$SECONDS
    while (( SECONDS - t0 < RUN_TIMEOUT_S )); do
        now=$(wc -l < "$RESULTS" 2>/dev/null || echo 0)
        (( now > before )) && break
        sleep 2
    done
    # let oa_eval_node land before the kill (cosmetic in SITL, keeps logs tidy)
    sleep 5
    kill "$LPID" 2>/dev/null
    killall_stack
    now=$(wc -l < "$RESULTS" 2>/dev/null || echo 0)
    if (( now > before )); then
        tail -1 "$RESULTS" | python3 -c "import json,sys; r=json.load(sys.stdin); print('CLEAN' if r['clean'] else 'FAIL', r['reasons'], 'min wall', r['min_wall_clearance_m'], 'min obstacle', r['min_obstacle_clearance_m'], 'passes', r['passes'])"
    else
        echo "NO RESULT within ${RUN_TIMEOUT_S}s (see $RUN_DIR/ros.log)"
        echo "{\"clean\": false, \"reasons\": [\"harness_timeout\"], \"planner\": \"$PLANNER\", \"tags\": {\"scenario\": \"$SCENARIO\", \"spacing_m\": $sp, \"dropout\": $DROPOUT, \"label\": \"$LABEL\", \"run\": \"$RUN\", \"fc\": \"$FC_SETS\"}}" >> "$RESULTS"
    fi
done

log "summary ($RESULTS)"
python3 "$HERE/oa_eval_report.py" "$RESULTS"
